#!/usr/bin/env python3
# make_palisade_6643.py — ПАТЧ 66.43 (приказ 6 владельца): «ПОЛНОСТЬЮ
# ПЕРЕДЕЛАТЬ ТАЙЛЫ ОГРАДЫ ДЕРЕВНИ — НОРМАЛЬНЫЙ ДЕРЕВЯННЫЙ ЧАСТОКОЛ».
#
# ДИАГНОЗ: прежний palisade_0 (66.7) — ОДИН широкий колж (22px) с округлым
# конусом по центру тайла и просветами травы: на карте ряд читался как
# «бочки/стога», а не стена.
#
# НОВЫЙ ТАЙЛ 32×32 — классический частокол «конец в конец»:
#   * ДВА тесно составленных бревна на тайл (16px каждое) — соседние тайлы
#     продолжают ряд БЕЗ разрывов: шов между тайлами = шов между брёвнами;
#   * бревна заострены НАКЛОННЫМИ СРЕЗАМИ (апексы на разной высоте —
#     плетёный ритм высокий/низкий), остриё целиком внутри тайла;
#   * кора: тёмный контур, световая грань слева (солнце верх-лево, как у
#     фасадов/боевых листов), волокна, сучок;
#   * ГОРИЗОНТАЛЬНАЯ ОБВЯЗКА (лежень) поперёк брёвен с гвоздями — стена
#     читается единой конструкцией, а не столбиками;
#   * тёмная земля и редкие травинки у основания.
# Идемпотентен: перегенерация по желанию. Выход: assets/tiles/palisade_0.png
import os
from PIL import Image, ImageDraw

OUT = '/home/z/my-project/sosnowda.github.io/game/assets/tiles'
TS = 32

# Палитра (дерево честного частокола, свет верх-лево)
BARK_L = (150, 116, 72, 255)    # световая грань
BARK = (116, 88, 54, 255)       # основной фон коры
BARK_M = (98, 74, 44, 255)      # тень справа
BARK_D = (74, 54, 32, 255)      # глубокая тень
OUTL = (38, 26, 12, 255)        # контур
TIP_L = (164, 132, 86, 255)     # срез острия — свет
BEAM = (86, 64, 40, 255)        # лежень
BEAM_L = (110, 86, 56, 255)     # лежень — верхний блик
BEAM_D = (56, 40, 24, 255)      # лежень — тень
NAIL = (30, 22, 14, 255)
EARTH = (44, 32, 18, 210)
GRASS = (58, 92, 44, 255)
GRASS_L = (76, 112, 54, 255)


def log_shape(d, x0, apex_x, apex_y, cut_l_y, cut_r_y):
    """Одно бревно: наклонный срез (апекс) + тело до низа тайла."""
    x1 = x0 + 15
    # контур острия: срез от левого края к апексу, затем вниз к правому краю
    d.polygon([(x0, cut_l_y), (apex_x, apex_y), (x1, cut_r_y),
               (x1, TS), (x0, TS)], fill=BARK, outline=OUTL)
    # световая срезанная грань вдоль ската
    d.line([(x0 + 1, cut_l_y + 1), (apex_x, apex_y + 1)], fill=TIP_L, width=1)
    # световая грань слева (солнце верх-лево)
    d.line([(x0 + 1, cut_l_y + 1), (x0 + 1, TS - 1)], fill=BARK_L, width=1)
    # тень справа
    d.line([(x1 - 1, cut_r_y + 1), (x1 - 1, TS - 1)], fill=BARK_D, width=2)
    # волокна
    for fx in range(x0 + 4, x1 - 2, 4):
        d.line([(fx, max(cut_l_y, cut_r_y) + 2), (fx, TS)], fill=BARK_M, width=1)


def make_palisade(name='palisade_0'):
    c = Image.new('RGBA', (TS, TS), (0, 0, 0, 0))
    d = ImageDraw.Draw(c)

    # --- земля у основания (подо ВСЕМ тайлом, читается и в просветах срезов)
    d.rectangle([0, TS - 3, TS - 1, TS - 1], fill=EARTH)

    # --- ДВА бревна 16px: шов между тайлами = шов между брёвнами
    # бревно A: апекс высоко, срез наклонён вниз-вправо
    log_shape(d, 0, apex_x=5, apex_y=1, cut_l_y=6, cut_r_y=10)
    # бревно B: апекс ниже (ритм высокий/низкий), срез наклонён вниз-влево
    log_shape(d, 16, apex_x=27, apex_y=4, cut_l_y=10, cut_r_y=8)

    # сучок на бревне B
    d.ellipse([24, 15, 27, 17], fill=BARK_D, outline=OUTL)

    # --- ГОРИЗОНТАЛЬНАЯ ОБВЯЗКА (лежень) поперёк обоих брёвен
    d.rectangle([0, 21, TS - 1, 25], fill=BEAM)
    d.line([(0, 21), (TS - 1, 21)], fill=BEAM_L, width=1)
    d.line([(0, 25), (TS - 1, 25)], fill=BEAM_D, width=1)
    d.rectangle([0, 21, TS - 1, 25], outline=OUTL)
    # гвозди по центрам брёвен
    for nx in (7, 23):
        d.point((nx, 23), fill=NAIL)

    # --- травинки у основания (редкие, не «просветы»)
    for gx, gy in ((6, 30), (18, 29), (27, 30), (11, 28)):
        d.point((gx, gy), fill=GRASS)
        d.point((gx, gy - 1), fill=GRASS_L)

    c.save(os.path.join(OUT, name + '.png'))
    print('OK', name, c.size, '- частокол: 2 бревна + наклонные срезы + лежень')


if __name__ == '__main__':
    make_palisade()
