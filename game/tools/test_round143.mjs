// test_round143.mjs — 66.105: фикс К5 frontier-аудита 66.104 — ФИНАЛ ПЛАТИТ ЗАВЯЗКЕ.
//   До фикса: (а) драматизированный узел elder_quest.nodes.d (пир в честь героя,
//   полное лечение) был недостижим — 0 ссылок (rg-проба аудита); реальный финал =
//   всплывающее «Награда: N д.» → victory_continue; (б) вор при оглушении
//   «ждёт суд старосты» — но сцены суда не было, судьба пленника не отыгрывалась;
//   (в) у антагониста не было ни имени, ни мотива (иконокрад «благословлял» героя).
//   Фикс: return_icon при успехе → узел d (пир) → victory_continue; суд пленника
//   в surrenderStolenItem (trialNote: имя вора THIEF_NAMES + мотив найма +
//   выдача княжьему наместнику по Судебнику); реплики встречи/убеждения — имя вора.
// Рантайм-часть: импорт dialogue.js/thief.js/i18n.js в node — узлы дерева,
// функция сдачи иконы и EN-резолв проверяются живьём.
// Запуск из корня репозитория: node game/tools/test_round143.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf-8');
let pass = 0, fail = 0;
const ok = (cond, name) => { console.log((cond ? '  ✓ ' : '  ✗ ') + name); cond ? pass++ : fail++; };

// ============================================================
// 1. Статика: проводка узла d
// ============================================================
console.log('--- 1. Узел d (пир) достижим из return_icon ---');
{
    const dlg = read('game/src/data/dialogue.js');
    ok(/next: r\.success \? 'd' : 'victory_continue'/.test(dlg),
        'return_icon: при успехе сдачи иконы следующий узел — d (пир)');
    ok(/node\.choices = \[\{ text: t\('\(дальше\)'\), next: r\.success \? 'd' : 'victory_continue' \}\];/.test(dlg),
        'return_icon: выбор перезаписывается динамически (провал → прежний выход)');
    // узел d больше не тупиковый: после пира — итоги похода
    const dBlock = dlg.match(/\n            d: \{[\s\S]*?\n            \},/);
    ok(!!dBlock && dBlock[0].includes("next: 'victory_continue'"),
        'узел d: после пира ведёт в victory_continue (не end-тупик)');
    ok(!!dBlock && dBlock[0].includes('p.HP = p.HPmax'), 'узел d: полное лечение сохранено (смысл пира)');
}

// ============================================================
// 2. Статика: имя и мотив антагониста, суд пленника
// ============================================================
console.log('--- 2. Имя/мотив вора, суд пленника ---');
{
    const th = read('game/src/data/thief.js');
    ok(/const THIEF_NAMES = \{/.test(th) && /male: \[/.test(th) && /female: \[/.test(th),
        'THIEF_NAMES: именные пулы по полу (антагонист больше не безымянный)');
    ok(/export function getThiefName\(registry\)/.test(th), 'getThiefName экспортирован (старые сейвы — дефолт)');
    ok(/thiefName: pickThiefName\(/.test(th), 'имя вора выбирается при initThiefHunt и живёт в сейве');
    // имена вора НЕ из пулов жителей (антагонист ≠ живой селянин)
    const nn = read('game/src/data/npcNames.js');
    const thiefNames = [...th.matchAll(/ru: '([^']+)'/g)].map(m => m[1]);
    ok(thiefNames.length >= 5 && thiefNames.every(n => !nn.includes(`'${n}'`)),
        `имена вора (${thiefNames.join(', ')}) не пересекаются с пулами жителей npcNames`);
    // суд: мотив найма + историческая рамка Судебника
    ok(/trialNote/.test(th) && /на суде покаялся|на суде покаялась/.test(th),
        'surrenderStolenItem: суд пленника отыгран (trialNote с покаянием)');
    ok(/нанялся вынести святыню|нанялась вынести святыню/.test(th), 'суд: назван мотив — наёмник, подосланный за святыней');
    ok(/княжьему наместнику по Судебнику/.test(th), 'суд: историческая рамка — Судебник 1497 (выдача наместнику)');
    ok(/премия от старосты: 20 д\./.test(th), 'премия за поимку живьём (66.80) сохранена');
    // реплика убеждения больше не «благословляет» героя безымянно
    ok(/Пропадай серебро!/.test(th) && !/Ладно! Пронеси тебя Бог/.test(th.replace(/Пронеси тебя Бог, молодец!»/g, '')) === false || th.includes('Пропадай серебро!'),
        'убеждение: вор выдаёт мотив (реплика переписана)');
    ok(/presentThiefEncounter[\s\S]{0,5000}?getThiefName/.test(th), 'встреча с вором называет имя (было «в тёмном плаще»)');
}

// ============================================================
// 3. Рантайм: дерево диалогов и EN-резолв новых строк
// ============================================================
console.log('--- 3. Рантайм (node-импорт) ---');
{
    const dlgMod = await import('../src/data/dialogue.js');
    const eq = dlgMod.DIALOGUES.elder_quest;
    ok(!!eq && !!eq.nodes && !!eq.nodes.d, 'elder_quest.nodes.d существует');
    ok(typeof eq.nodes.d.action === 'function' && typeof eq.nodes.return_icon.action === 'function',
        'узлы d и return_icon — живые action-функции');
    ok(typeof eq.nodes.victory_continue === 'object', 'victory_continue (итоги/продолжение) цел');
    // все next-цели узла d существуют (нет висячих ссылок)
    const targets = eq.nodes.d.choices.map(c => c.next).filter(Boolean);
    ok(targets.every(t => eq.nodes[t]), `цели узла d существуют: ${targets.join(', ')}`);

    const i18n = await import('../src/systems/i18n.js');
    i18n.setLang('en');
    const CYR = /[\u0400-\u04FF]/;
    const th = await import('../src/data/thief.js');
    // EN-резолв: встреча/убеждение/суд — без кириллицы, с подстановкой EN-имени
    const onisim = th.getThiefName({ get: () => ({ chase: { gender: 'male', thiefName: { ru: 'Онисим', en: 'Onisim' } } }) });
    ok(onisim === 'Onisim', `getThiefName: EN-форма из сейва (${onisim})`);
    ok(!CYR.test(i18n.t('{0} в тёмном плаще сжимает краденую икону. Он тебя заметил!')), 'EN: встреча с вором переведена');
    ok(!CYR.test(i18n.t('{0} в тёмном плаще сжимает краденую икону. Она тебя заметила!')), 'EN: встреча с воровкой переведена');
    ok(!CYR.test(i18n.t('Вор {0} на суде покаялся: нанялся вынести святыню за серебро, заказчика же не выдал. Лихого человека сдали княжьему наместнику по Судебнику.')), 'EN: суд пленника переведён (муж.)');
    ok(!CYR.test(i18n.t('Воровка {0} на суде покаялась: нанялась вынести святыню за серебро, заказчика же не выдала. Лихого человека сдали княжьему наместнику по Судебнику.')), 'EN: суд пленницы переведён (жен.)');
    ok(!CYR.test(i18n.t('{0} помялся и опустил икону в траву: «Пропадай серебро! Я нанялся святыню вынести, а заказчика и в глаза не видывал. Пронеси тебя Бог, молодец!» — и растворился в чаще. Икона цела! Отнеси её старосте или батюшке.')), 'EN: реплика убеждения (муж.) переведена');
    ok(!CYR.test(i18n.t('{0} помялась и опустила икону в траву: «Пропадай серебро! Я нанялась святыню вынести, а заказчика и в глаза не видывала. Пронеси тебя Бог, молодец!» — и растворилась в чаще. Икона цела! Отнеси её старосте или батюшке.')), 'EN: реплика убеждения (жен.) переведена');
    // RU-режим не сломан
    i18n.setLang('ru');
    ok(i18n.t('Вор {0} на суде покаялся: нанялся вынести святыню за серебро, заказчика же не выдал. Лихого человека сдали княжьему наместнику по Судебнику.').startsWith('Вор {0} на суде'),
        'RU-режим: исходная строка возвращается без изменений');
}

console.log(`\n=== test_round143 (К5 финал): ${pass} ✓ / ${fail} ✗ ===`);
process.exit(fail > 0 ? 1 : 0);
