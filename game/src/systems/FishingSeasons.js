// FishingSeasons.js — СЕЗОННЫЕ ЗАПРЕТЫ И БОНУСЫ РЫБАЛКИ (раунд 66.7,
// приказ владельца п.4: «сезонные запреты/бонусы рыбалки»).
//
// Календарь игры — сентябрьский (месяц 0 = сентябрь … 11 = август).
// По народному календарю и промысловой логике XV века:
//
//   сентябрь(0)–октябрь(1)  — ОСЕННИЙ ЖОР: рыба жирует перед зимой,
//                             берёт жадно (БОНУС +2 ❤ к улову);
//   ноябрь(2)               — ледостав: клёв обычный, до льда;
//   декабрь(3)–февраль(5)   — ЗИМА: ловля из ЛУНКИ (уже была в игре),
//                             налим берёт в стужу — без изменений;
//   март(6)                 — последняя вода открытой воды — обычный клёв;
//   апрель(7)–май(8)        — НЕРЕСТ: рыба у берегов метать икру —
//                             ЗАПРЕТ (ловить грех, деревня осудит);
//   июнь(9)–август(11)      — летний лов: обычный клёв (в дождь —
//                             погодный бонус +1, как и было).
//
// Используется в LocationScene.goFishing(): фаза решает, состоится ли
// рыбалка вовсе (нерест — запрет) и насколько щедрым будет улов.

import { t } from './i18n.js';

/**
 * Сезон рыбалки для месяца (timeState.month, 0 = сентябрь).
 * @returns {{id: string, blocked: boolean, bonus: number,
 *            title: string, toast: string, log: string}}
 *   blocked — рыбалка недоступна (нерест); bonus — прибавка к улову.
 */
export function fishingSeason(month) {
    const m = ((month % 12) + 12) % 12;
    if (m === 7 || m === 8) {
        return {
            id: 'spawning',
            blocked: true,
            bonus: 0,
            title: t('🎣 Нерест'),
            toast: t('Рыба у берегов нерестится — удочки убраны до лета.'),
            log: t('Ходил к реке с удочкой — но у берега нерест. Рыбу не ловим, грех.'),
        };
    }
    if (m === 0 || m === 1) {
        return {
            id: 'autumn_feed',
            blocked: false,
            bonus: 2,
            title: t('🎣 Рыбалка — жор'),
            toast: t('Осенний жор: рыба берёт жадно, наедаясь перед зимой.'),
            log: t('Осенний жор — рыба идёт на крючок смело.'),
        };
    }
    if (m === 3 || m === 4 || m === 5) {
        return {
            id: 'ice',
            blocked: false,
            bonus: 0,
            title: t('🎣 Лунка во льду'),
            toast: t('Река под льдом — ловля из лунки, налим берёт в стужу.'),
            log: '',
        };
    }
    return {
        id: 'normal',
        blocked: false,
        bonus: 0,
        title: t('🎣 Рыбалка'),
        toast: '',
        log: '',
    };
}
