// Раунд 66.21 (приказы 9–12): часы доступа в здания.
// Раунд 66.22 (приказы 1–2): РАССВЕТ И ЗАКАТ РАССЧИТЫВАЮТСЯ по времени
// года и дате (широта Новгородской земли ≈ 58.5° с.ш.): жилые дома
// открываются С РАССВЕТОМ и запираются ПО ЗАКАТУ — летом ночь коротка
// (двери заперты ~21:15–02:50), зимой долга (~15:10–08:50).
// 11\ Церковь закрыта ночью; открыта на богослужебное время и на 2–3 часа
//     после богослужений (после обедни — 3 часа, после вечерни — 2).
//
// Чистые функции без Phaser — покрываются юнит-тестом (test_round82).

/**
 * Число дней в месяцах игрового календаря (месяц 0 = сентябрь).
 */
const MONTH_DAYS = [30, 31, 30, 31, 31, 28, 31, 30, 31, 30, 31, 31];

/**
 * Раунд 66.22: номер дня солнечного года (1..365) по игровой дате.
 * Календарь начинается с 1 сентября — это 244-й день солнечного года.
 * @param {number} month 0..11 (0 = сентябрь)
 * @param {number} day 1..31
 * @returns {number} 1..365
 */
export function dayOfYear(month, day) {
    const m = ((Math.floor(month) % 12) + 12) % 12;
    const d = Math.max(1, Math.min(31, Math.floor(day) || 1));
    let doy = 0;
    for (let i = 0; i < m; i++) doy += MONTH_DAYS[i];
    doy += d;
    // 1 сентября = 244-й день григорианского солнечного года
    const n = (243 + doy) % 365;
    return n === 0 ? 365 : n;
}

/**
 * Раунд 66.22 (приказ 2): РАССЧЁТ РАССВЕТА И ЗАКАТА по времени года и дате.
 * Стандартная солнечная формула: склонение через косинус года, часовой угол
 * через широту φ = 58.5° с.ш. (Новгородская земля), зенит 90.833° —
 * официальный восход (диск + рефракция).
 * @param {number} month 0..11 (0 = сентябрь)
 * @param {number} day 1..31
 * @returns {{ sunrise: number, sunset: number, dayLen: number }} часы (дробные)
 */
export function sunTimes(month, day) {
    const LAT = 58.5 * Math.PI / 180;   // Новгородская земля
    const RAD = Math.PI / 180;
    const n = dayOfYear(month, day);
    // Склонение солнца (гра­дусы): максимум +23.44 (лето), минимум −23.44 (зима)
    const decl = -23.44 * RAD * Math.cos(2 * Math.PI * (n + 10) / 365);
    // Часовой угол: cos H = (cos(зенит) − sin φ·sin δ) / (cos φ·cos δ)
    const zen = 90.833 * RAD;
    let cosH = (Math.cos(zen) - Math.sin(LAT) * Math.sin(decl)) / (Math.cos(LAT) * Math.cos(decl));
    cosH = Math.max(-1, Math.min(1, cosH)); // страховка от полярного дня/ночи
    const H = Math.acos(cosH) / RAD;        // градусы
    const dayLen = 2 * H / 15;              // часов светового дня
    // Полдень принимаем за 12:00 (уравнением времени для игры пренебрегаем)
    const sunrise = Math.round((12 - dayLen / 2) * 100) / 100;
    const sunset = Math.round((12 + dayLen / 2) * 100) / 100;
    return { sunrise, sunset, dayLen: Math.round(dayLen * 100) / 100 };
}

/**
 * Извлечь игровую дату { month, day } из timeState (или null).
 */
function dateOf(date) {
    if (!date) return null;
    if (typeof date.month === 'number' && typeof date.day === 'number') {
        return { month: date.month, day: date.day };
    }
    return null;
}

/**
 * Ночь ли в данный час.
 * С датой (раунд 66.22) — ночь ПО ЗАКАТУ до РАССВЕТА по времени года:
 *   { month, day } — месяцы 0..11 (0 = сентябрь), день 1..31.
 * Без даты — усреднённый канон 66.21: ночь 21:00–04:00.
 * @param {number} hour 0..23 (можно дробный)
 * @param {{ month: number, day: number }|object} [date] gameTime или {month, day}
 * @returns {boolean}
 */
export function isNightHour(hour, date) {
    const h = ((hour % 24) + 24) % 24;
    const d = dateOf(date);
    if (!d) return h >= 21 || h < 4; // канон 66.21 (без даты)
    const { sunrise, sunset } = sunTimes(d.month, d.day);
    return h >= sunset || h < sunrise; // 66.22: заперто ПО ЗАКАТУ, открыто С РАССВЕТА
}

// Богослужения отца Савватия (канон npcSchedules/npcPresence):
//   утреня — рассвѣт 4:00–6:00, обедня — утро 6:00–12:00, вечерня — вечеръ 16:00–19:00.
// Открыта: на службе + после неё. После утрени/обедни (непрерывно с 4:00) — 3 часа
// после конца обедни (до 15:00); после вечерни — 2 часа (до 21:00).
// Закрыта: 15:00–16:00 (батюшка на отдыхе после трапезы) и ночью 21:00–04:00.
// Раунд 66.22: церковное время — каноническое (службы по церковному уставу),
// поэтому окна церкви НЕ привязаны к солнцу — только жилые дома идут по солнцу.

/** Начало/конец дневного окна церкви (утреня+обедня+3 ч) и вечернего (вечерня+2 ч). */
export const CHURCH_WINDOWS = [
    { start: 4, end: 15 },   // утреня 4–6, обедня 6–12, +3 ч после обедни
    { start: 16, end: 21 },  // вечерня 16–19, +2 ч после вечерни
];

/** Открыта ли церковь в данный час. */
export function isChurchOpen(hour) {
    const h = ((hour % 24) + 24) % 24;
    return CHURCH_WINDOWS.some(w => h >= w.start && h < w.end);
}

/**
 * Человеческое пояснение, почему церковь заперта (для поп-апа у двери).
 * @returns {string} ключ-строка RU (локализуется t() у вызывателя)
 */
export function churchClosedReason(hour) {
    const h = ((hour % 24) + 24) % 24;
    if (isNightHour(h)) return 'Ночь. Церковь заперта — богослужение начнётся на рассвете.';
    return 'Батюшка отдыхает после трапезы. Церковь откроют к вечерне.';
}
