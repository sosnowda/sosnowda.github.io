// Раунд 66.21 (приказы владельца 9–12): часы доступа в здания.
// 9\  Все ЖИЛЫЕ дома закрыты по ночам.
// 11\ Церковь закрыта ночью; открыта на богослужебное время и на 2–3 часа
//     после богослужений (после обедни — 3 часа, после вечерни — 2).
//
// Чистые функции без Phaser — покрываются юнит-тестом (test_round82).

/**
 * Ночь ли в данный час (по канону TimeSystem: ночь 21:00–04:00).
 * В 4:00 начинается рассвѣт — люди встают, двери открывают.
 * @param {number} hour 0..23
 * @returns {boolean}
 */
export function isNightHour(hour) {
    const h = ((hour % 24) + 24) % 24;
    return h >= 21 || h < 4;
}

// Богослужения отца Савватия (канон npcSchedules/npcPresence):
//   утреня — рассвѣт 4:00–6:00, обедня — утро 6:00–12:00, вечерня — вечеръ 16:00–19:00.
// Открыта: на службе + после неё. После утрени/обедни (непрерывно с 4:00) — 3 часа
// после конца обедни (до 15:00); после вечерни — 2 часа (до 21:00).
// Закрыта: 15:00–16:00 (батюшка на отдыхе после трапезы) и ночью 21:00–04:00.

/** Начало/конец дневного окна церкви (утреня+обедня+3 ч) и вечернего (вечерня+2 ч). */
export const CHURCH_WINDOWS = [
    { start: 4, end: 15 },   // утреня 4–6, обедня 6–12, +3 ч после обедни
    { start: 16, end: 21 },  // вечерня 16–19, +2 ч после вечерни
];

/** Открыта ли церковь в данный час. */
export function isChurchOpen(hour) {
    const h = ((hour % 24) + 24) % 24;
    return CHURCH_WINDOWS.some(w => h >= w.start && h < w.end);
}

/**
 * Человеческое пояснение, почему церковь заперта (для поп-апа у двери).
 * @returns {string} ключ-строка RU (локализуется t() у вызывателя)
 */
export function churchClosedReason(hour) {
    const h = ((hour % 24) + 24) % 24;
    if (isNightHour(h)) return 'Ночь. Церковь заперта — богослужение начнётся на рассвете.';
    return 'Батюшка отдыхает после трапезы. Церковь откроют к вечерне.';
}
