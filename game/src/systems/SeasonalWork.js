/**
 * Работа месяца. timeState — из getTime(registry); без времени — лето/сенокос
 * (безопасный дефолт для меню).
 */
export function getSeasonalWork(timeState) {
    const month = timeState ? ((timeState.month % 12) + 12) % 12 : 9;
    const row = MONTH_WORK[month] || MONTH_WORK[9];
    const phase = FIELD_PHASES[row.phase] ? row.phase : 'fallow';
    return {
        month,
        phase,
        phaseId: FIELD_PHASES[phase],
        work: tI18n(row.work),
        name: tI18n(WORK_NAMES[phase] || ''),
        toast: tI18n(PHASE_TOASTS[phase] || ''),
    };
}

/** Фаза поля месяца (для рисования). */
export function fieldPhaseOf(timeState) {
    return getSeasonalWork(timeState).phase;
}

/** Случайная реплика работника по фазе. */
export function seasonalWorkerLine(phase) {
    const lines = PHASE_LINES[phase] || PHASE_LINES.fallow;
    return tI18n(lines[Math.floor(Math.random() * lines.length)]);
}

/** Список месяцев с работами (для юнит-тестов). */
export function seasonalWorkTable() {
    return Object.keys(MONTH_WORK).map(Number).sort((a, b) => a - b)
        .map((m) => ({ month: m, ...MONTH_WORK[m] }));
}
